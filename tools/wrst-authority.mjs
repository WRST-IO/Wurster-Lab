const here = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(here, '..');
const authorityDir = path.join(rootDir, 'authority', 'wrst.io');
const publicDir = path.join(authorityDir, 'public');
const privateDir = path.join(authorityDir, 'private');
const runtimeDesktopDir = path.join(rootDir, 'runtime', 'desktop', 'src');
