const AUTHORITY = 'wrst.io';

function authorityDiscovery() {
  return {
    format: 'wurst/authority-discovery-1',
    service: 'WRST.IO Wurst Authority',
    authority: AUTHORITY,
    protocol: 'wurst/authority-api-2',
    identity: 'project',
    offlineVerification: true,
    trust: {
      root: '/.well-known/wurst-authority-root.json',
      bundle: '/.well-known/wurst-trust-bundle.json'
    },
    claims: {
      domain: { supported: true, method: 'dns-txt' },
      email: { supported: true, method: 'email-code', from: 'oink@wrst.io' }
    },
    issuance: {
      baseUrl: 'https://authority.wrst.io',
      endpoints: {
        domainChallenge: '/v1/domain/challenge',
        domainCertificate: '/v1/domain/certificate',
        emailChallenge: '/v1/email/challenge',
        emailCertificate: '/v1/email/certificate'
      }
    }
  };
}

function flagsFrom(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token.startsWith('--')) { out._.push(token); continue; }
    const key = token.slice(2);
    const next = argv[i + 1];
    if (next && !next.startsWith('--')) { out[key] = next; i += 1; }
    else out[key] = true;
  }
  return out;
}

async function readJson(file) { return JSON.parse(await fs.readFile(file, 'utf8')); }
async function writeJson(file, value, mode = 0o644) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, `${JSON.stringify(value, null, 2)}\n`, { mode });
}
async function readPhraseFile(file) { return file ? (await fs.readFile(path.resolve(file), 'utf8')).trim() : null; }
function assertCeremonyPhrase(value, expectedTokens, label) {
  if (!value) return;
  const count = String(value).normalize('NFKC').trim().split(/\s+/).filter(Boolean).length;
  if (count !== expectedTokens) throw new Error(`${label} must contain exactly ${expectedTokens} space-separated Meatphrase tokens for production bootstrap`);
}
async function promptHidden(label) {
  if (!process.stdin.isTTY) throw new Error(`${label.trim()} requires a TTY or --issuer-meatphrase-file`);
  process.stderr.write(label);
  process.stdin.setRawMode(true);
  process.stdin.resume();
  process.stdin.setEncoding('utf8');
  let value = '';
  return new Promise((resolve, reject) => {
    const onData = (char) => {
      if (char === '\u0003') { cleanup(); reject(new Error('Cancelled')); return; }
      if (char === '\r' || char === '\n') { cleanup(); process.stderr.write('\n'); resolve(value.trim()); return; }
      if (char === '\u007f') { value = value.slice(0, -1); return; }
      value += char;
    };
    const cleanup = () => { process.stdin.off('data', onData); process.stdin.setRawMode(false); process.stdin.pause(); };
    process.stdin.on('data', onData);
  });
}

async function syncPublic() {
  const root = await readJson(path.join(publicDir, 'root.json'));
  const issuer = await readJson(path.join(publicDir, 'issuer.json'));
  const trustBundle = await readJson(path.join(publicDir, 'trust-bundle.json'));

  await writeJson(path.join(runtimeDesktopDir, 'trusted-authorities.json'), [root]);
  await writeJson(path.join(runtimeDesktopDir, 'trust-bundle.json'), trustBundle);
  await writeJson(path.join(runtimeWebDir, 'trusted-authorities.json'), [root]);
  await writeJson(path.join(runtimeWebDir, 'trust-bundle.json'), trustBundle);
  await fs.writeFile(webTrustGenerated, `// Generated by tools/wrst-authority.mjs sync. Public material only.\nexport const TRUSTED_AUTHORITIES = ${JSON.stringify([root], null, 2)};\nexport const TRUST_BUNDLE = ${JSON.stringify(trustBundle, null, 2)};\n`);
  await fs.writeFile(meatgrinderTrustGenerated, `// Generated by tools/wrst-authority.mjs sync. Public material only.\nexport const TRUSTED_AUTHORITIES = ${JSON.stringify([root], null, 2)};\nexport const TRUST_BUNDLE = ${JSON.stringify(trustBundle, null, 2)};\n`);

  await fs.mkdir(siteWellKnownDir, { recursive: true });
  await writeJson(path.join(siteWellKnownDir, 'wurst-authority'), authorityDiscovery());
  await writeJson(path.join(siteWellKnownDir, 'wurst-authority-root.json'), root);
  await writeJson(path.join(siteWellKnownDir, 'wurst-trust-bundle.json'), trustBundle);

  await fs.mkdir(path.dirname(workerGenerated), { recursive: true });
  const generated = `// Generated by tools/wrst-authority.mjs sync. Public material only.\nexport const AUTHORITY_ROOT = ${JSON.stringify(root, null, 2)};\nexport const ISSUER_CERTIFICATE = ${JSON.stringify(issuer, null, 2)};\n`;
  await fs.writeFile(workerGenerated, generated);
  console.log('✓ synchronized WRST.IO public trust material into runtimes, static /.well-known discovery and the issuing Worker');
}

async function bootstrap(flags) {
  if ((!process.stdin.isTTY || !process.stdout.isTTY) && !flags['allow-noninteractive']) {
    throw new Error('Authority bootstrap requires an interactive terminal. Refusing to generate a Root into CI/log output. Use --allow-noninteractive only for disposable tests.');
  }
  await fs.mkdir(publicDir, { recursive: true });
  await fs.mkdir(privateDir, { recursive: true });
  const rootPath = path.join(publicDir, 'root.json');
  try {
    const existing = await readJson(rootPath);
    if (!existing.development && !flags['replace-production-root']) throw new Error(`Production root already exists at ${path.relative(rootDir, rootPath)}. Refusing to replace it. Root replacement requires the explicit --replace-production-root disaster-recovery flag.`);
    if (existing.development) console.log('↻ replacing the bundled WRST.IO development root with a production root');
  } catch (error) {
    if (error.code !== 'ENOENT' && !String(error.message).includes('already exists')) throw error;
    if (String(error.message).includes('already exists')) throw error;
  }

  const suppliedRootPhrase = await readPhraseFile(flags['root-meatphrase-file']);
  assertCeremonyPhrase(suppliedRootPhrase, 24, 'Root Meatphrase');
  const createdAt = new Date().toISOString();
  const root = createAuthorityRoot({ authority: AUTHORITY, name: 'WRST.IO Root Authority', meatphrase: suppliedRootPhrase, createdAt });
  const issuerExpiry = new Date(Date.now() + 5 * 365 * 24 * 60 * 60 * 1000).toISOString();
  const suppliedIssuerPhrase = await readPhraseFile(flags['issuer-meatphrase-file']);
  assertCeremonyPhrase(suppliedIssuerPhrase, 16, 'Issuer Meatphrase');
  const issuer = createAuthorityIssuer({
    authority: AUTHORITY,
    rootMeatphrase: root.meatphrase,
    rootPublic: root.publicRecord,
    issuerId: `wrst.io-issuer-${new Date().getUTCFullYear()}-01`,
    name: `WRST.IO Issuing Authority ${new Date().getUTCFullYear()}`,
    issuerMeatphrase: suppliedIssuerPhrase,
    issuedAt: createdAt,
    expiresAt: issuerExpiry
  });
  const trustBundle = createTrustBundle({
    authority: AUTHORITY,
    rootMeatphrase: root.meatphrase,
    rootPublic: root.publicRecord,
    version: 1,
    issuers: [issuer.certificate],
    revokedIssuers: [],
    revokedPublishers: [],
    generatedAt: createdAt
  });

  await writeJson(rootPath, root.publicRecord);
  await writeJson(path.join(publicDir, 'issuer.json'), issuer.certificate);
  await writeJson(path.join(publicDir, 'trust-bundle.json'), trustBundle);
  await writeJson(path.join(privateDir, 'issuer.wurstissuer'), issuer.bundle, 0o600);
  await syncPublic();

  console.log('\n🐷 WRST.IO AUTHORITY BOOTSTRAPPED');
  console.log(`   root fingerprint:   ${root.fingerprint}`);
  console.log(`   issuer fingerprint: ${issuer.fingerprint}`);
  console.log(`   issuer valid until: ${issuerExpiry}`);
  console.log('\n════════════════════════════════════════════════════════════════════');
  console.log('ROOT MEATPHRASE — PRINT THIS, VERIFY THE FINGERPRINT, THEN STORE OFFLINE');
  console.log('════════════════════════════════════════════════════════════════════');
  console.log(root.meatphrase);
  console.log(`\nRoot fingerprint: ${root.fingerprint}`);
  console.log('The root private key is derived from this phrase and is NOT written to disk.');
  console.log('After printing: run npm run authority:root-check and type the phrase back from paper.');
  console.log('\n────────────────────────────────────────────────────────────────────');
  console.log('ISSUER MEATPHRASE — protects the encrypted online issuer backup');
  console.log('────────────────────────────────────────────────────────────────────');
  console.log(issuer.meatphrase);
  console.log(`\nEncrypted issuer backup: ${path.relative(rootDir, path.join(privateDir, 'issuer.wurstissuer'))}`);
  console.log('This private/ directory is gitignored and excluded from Wurster Lab exports.');
  console.log('\nNext: npm run authority:worker-secret  (then pipe/set the result as Cloudflare secret WRST_ISSUER_PRIVATE_PKCS8)');
}

async function verifySetup({ production = false } = {}) {
  const root = await readJson(path.join(publicDir, 'root.json'));
  const issuer = await readJson(path.join(publicDir, 'issuer.json'));
  const bundle = await readJson(path.join(publicDir, 'trust-bundle.json'));
  if (production && root.development) throw new Error('The active wrst.io root is the bundled DEVELOPMENT root. Run npm run authority:bootstrap on the trusted operator machine before production.');
  const issuerStatus = verifyAuthorityIssuerCertificate(issuer, [root]);
  const bundleStatus = verifyTrustBundle(bundle, [root]);
  if (issuerStatus.status !== 'verified') throw new Error(`Issuer chain is ${issuerStatus.status}: ${issuerStatus.error || 'not trusted'}`);
  if (bundleStatus.status !== 'verified') throw new Error(`Trust bundle is ${bundleStatus.status}: ${bundleStatus.error || 'not trusted'}`);
  if (!bundle.statement.issuers.some((candidate) => candidate.statement?.issuer?.fingerprint === issuer.statement?.issuer?.fingerprint)) throw new Error('Trust bundle does not contain the active issuer');
  console.log('✓ wrst.io root fingerprint:', root.fingerprint);
  console.log('✓ issuing chain:', issuer.statement.issuer.name, issuer.statement.issuer.fingerprint);
  console.log('✓ trust bundle:', `v${bundle.statement.version}`, bundle.statement.generatedAt);
}


async function rootPhraseFromFlags(flags) {
  return await readPhraseFile(flags['root-meatphrase-file']) || await promptHidden('Root Meatphrase: ');
}


async function rootCheck(flags) {
  const root = await readJson(path.join(publicDir, 'root.json'));
  const phrase = await rootPhraseFromFlags(flags);
  const derived = deriveAuthorityRoot({ authority: AUTHORITY, name: root.name, meatphrase: phrase, createdAt: root.createdAt ?? null });
  try {
    if (derived.fingerprint !== root.fingerprint || derived.publicRecord.publicKeySpki !== root.publicKeySpki) throw new Error('Root Meatphrase does NOT match the pinned wrst.io Root');
    console.log(`✓ Root Meatphrase matches ${root.fingerprint}`);
  } finally {
    // KeyObject lifetime is process-bound; no private bytes are serialized here.
  }
}

async function rotateIssuer(flags) {
  const root = await readJson(path.join(publicDir, 'root.json'));
  if (root.development && !flags.force) throw new Error('Refusing to rotate the bundled development issuer as production. Run bootstrap first, or pass --force only for lab work.');
  const rootMeatphrase = await rootPhraseFromFlags(flags);
  const issuerMeatphrase = await readPhraseFile(flags['issuer-meatphrase-file']);
  assertCeremonyPhrase(issuerMeatphrase, 16, 'Issuer Meatphrase');
  const oldIssuer = await readJson(path.join(publicDir, 'issuer.json'));
  const oldBundle = await readJson(path.join(publicDir, 'trust-bundle.json'));
  const now = new Date();
  const issuedAt = now.toISOString();
  const expiresAt = new Date(now.getTime() + 5 * 365 * 24 * 60 * 60 * 1000).toISOString();
  const sequence = String((oldBundle.statement?.issuers?.length || 0) + 1).padStart(2, '0');
  const issuer = createAuthorityIssuer({
    authority: AUTHORITY, rootMeatphrase, rootPublic: root,
    issuerId: `wrst.io-issuer-${now.getUTCFullYear()}-${sequence}`,
    name: `WRST.IO Issuing Authority ${now.getUTCFullYear()} #${sequence}`,
    issuerMeatphrase, issuedAt, expiresAt
  });
  const issuers = [...(oldBundle.statement?.issuers || [])];
  if (!issuers.some((item) => item?.statement?.issuer?.fingerprint === oldIssuer?.statement?.issuer?.fingerprint)) issuers.push(oldIssuer);
  issuers.push(issuer.certificate);
  const trustBundle = createTrustBundle({
    authority: AUTHORITY, rootMeatphrase, rootPublic: root, version: Number(oldBundle.statement?.version || 0) + 1,
    issuers, revokedIssuers: oldBundle.statement?.revokedIssuers || [], revokedPublishers: oldBundle.statement?.revokedPublishers || [], generatedAt: issuedAt
  });
  await writeJson(path.join(publicDir, 'issuer.json'), issuer.certificate);
  await writeJson(path.join(publicDir, 'trust-bundle.json'), trustBundle);
  await writeJson(path.join(privateDir, 'issuer.wurstissuer'), issuer.bundle, 0o600);
  await syncPublic();
  console.log(`\n✓ new issuer ${issuer.certificate.statement.issuer.issuerId}`);
  console.log(`  fingerprint: ${issuer.fingerprint}`);
  console.log(`  trust bundle: v${trustBundle.statement.version}`);
  console.log('\nISSUER MEATPHRASE — print/store with the encrypted issuer backup:');
  console.log(issuer.meatphrase);
}

async function revoke(flags) {
  const publisher = flags.publisher ? String(flags.publisher).trim().toLowerCase() : null;
  const issuer = flags.issuer ? String(flags.issuer).trim().toLowerCase() : null;
  if (!!publisher === !!issuer) throw new Error('Use exactly one of --publisher <fingerprint> or --issuer <fingerprint>');
  if (!/^[a-f0-9]{64}$/.test(publisher || issuer)) throw new Error('Revocation fingerprint must be 64 lowercase/uppercase hex characters');
  const root = await readJson(path.join(publicDir, 'root.json'));
  const bundle = await readJson(path.join(publicDir, 'trust-bundle.json'));
  const rootMeatphrase = await rootPhraseFromFlags(flags);
  const revokedPublishers = [...(bundle.statement?.revokedPublishers || [])];
  const revokedIssuers = [...(bundle.statement?.revokedIssuers || [])];
  if (publisher && !revokedPublishers.includes(publisher)) revokedPublishers.push(publisher);
  if (issuer && !revokedIssuers.includes(issuer)) revokedIssuers.push(issuer);
  const updated = createTrustBundle({
    authority: AUTHORITY, rootMeatphrase, rootPublic: root, version: Number(bundle.statement?.version || 0) + 1,
    issuers: bundle.statement?.issuers || [], revokedIssuers, revokedPublishers, generatedAt: new Date().toISOString()
  });
  await writeJson(path.join(publicDir, 'trust-bundle.json'), updated);
  await syncPublic();
  console.log(`✓ revoked ${publisher ? 'publisher' : 'issuer'} ${publisher || issuer} in trust bundle v${updated.statement.version}`);
}

async function workerRelaySecrets() {
  const settingsPath = path.join(privateDir, 'operator-settings.json');
  const settings = await readJson(settingsPath);
  if (settings?.format !== 'wrst/operator-settings-1') throw new Error('authority/wrst.io/private/operator-settings.json is missing or invalid');
  const relayUrl = String(settings.mailRelayUrl ?? '').trim();
  const relaySecret = String(settings.mailRelaySecret ?? '').trim();
  let parsed;
  try { parsed = new URL(relayUrl); } catch { throw new Error('Stored Mail Relay URL is invalid'); }
  if (parsed.protocol !== 'https:') throw new Error('Stored Mail Relay URL must use HTTPS');
  if (relaySecret.length < 32) throw new Error('Stored Mail Relay secret is too short');
  const workerDir = path.join(authorityDir, 'worker');
  const executable = process.platform === 'win32' ? 'npx.cmd' : 'npx';
  for (const [name, value] of [['WRST_MAIL_RELAY_URL', parsed.href], ['WRST_MAIL_RELAY_SECRET', relaySecret]]) {
    console.log(`→ uploading ${name} from sealed operator export`);
    const result = spawnSync(executable, ['wrangler', 'secret', 'put', name], {
      cwd: workerDir,
      input: `${value}\n`,
      stdio: ['pipe', 'inherit', 'inherit'],
      encoding: 'utf8'
    });
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error(`wrangler secret put ${name} exited with ${result.status}`);
  }
  console.log('✓ Mail Relay worker secrets uploaded from private operator settings');
}

async function workerSecret(flags) {
  const root = await readJson(path.join(publicDir, 'root.json'));
  if (root.development && !flags['allow-development']) throw new Error('Refusing to export a Cloudflare issuer secret while the bundled DEVELOPMENT root is active. Run authority:bootstrap first.');
  const bundle = await readJson(path.join(privateDir, 'issuer.wurstissuer'));
  const phrase = await readPhraseFile(flags['issuer-meatphrase-file']) || await promptHidden('Issuer Meatphrase: ');
  const key = unlockAuthorityIssuerPrivateKey(bundle, phrase);
  const der = key.export({ type: 'pkcs8', format: 'der' });
  process.stdout.write(`${der.toString('base64')}\n`);
  der.fill(0);
}

function help() {
  console.log(`\n🐷 WRST.IO Authority operator\n\nUsage:\n  node tools/wrst-authority.mjs bootstrap [--root-meatphrase-file file] [--issuer-meatphrase-file file] [--replace-production-root]\n  node tools/wrst-authority.mjs verify\n  node tools/wrst-authority.mjs production-check\n  node tools/wrst-authority.mjs root-check [--root-meatphrase-file file]\n  node tools/wrst-authority.mjs rotate-issuer [--root-meatphrase-file file] [--issuer-meatphrase-file file]\n  node tools/wrst-authority.mjs revoke --publisher <fingerprint> [--root-meatphrase-file file]\n  node tools/wrst-authority.mjs revoke --issuer <fingerprint> [--root-meatphrase-file file]\n  node tools/wrst-authority.mjs sync\n  node tools/wrst-authority.mjs worker-secret [--issuer-meatphrase-file file]\n  node tools/wrst-authority.mjs worker-relay-secrets\n\nbootstrap requires an interactive terminal and generates a 24-token Root Meatphrase by default. The Root private key is deterministic from that phrase and is never saved.\nThe separate issuer private key is stored encrypted under authority/wrst.io/private/, which is excluded from Git and release ZIPs.\n`);
}

const flags = flagsFrom(process.argv.slice(2));
const command = flags._[0];
try {
  if (command === 'bootstrap') await bootstrap(flags);
  else if (command === 'verify') await verifySetup();
  else if (command === 'production-check') await verifySetup({ production: true });
  else if (command === 'root-check') await rootCheck(flags);
  else if (command === 'rotate-issuer') await rotateIssuer(flags);
  else if (command === 'revoke') await revoke(flags);
  else if (command === 'sync') await syncPublic();
  else if (command === 'worker-secret') await workerSecret(flags);
  else if (command === 'worker-relay-secrets') await workerRelaySecrets();
  else help();
} catch (error) {
  console.error(`\n✗ ${error.message}`);
  process.exitCode = 1;
}
